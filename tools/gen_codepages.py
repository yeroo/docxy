"""Generate gridcore/src/codepage/tables.rs: the high halves (0x80-0xFF) of the
single-byte code pages the Text Import Wizard's File origin offers (#761).

Windows only. Each byte is decoded by the OS itself, with
kernel32.MultiByteToWideChar(page, 0, ...): that is what Excel on Windows reads
a text file with. Python's own codecs are not used, because they differ from
Windows (Python's mac_roman reads 0xDB as U+00A4, Windows' 10000 as U+20AC).

A byte the API cannot decode, or decodes to a private-use character (1253 0xAA
is U+F8F9 under the API's best fit), is undefined: U+FFFD, so no private-use
character reaches a cell. Windows-1252 is not here: textio keeps its own table,
whose five holes are the C1 control of the same number, as Windows decodes them.

Run from the repository root:  python tools/gen_codepages.py
CI never runs it; the generated file is committed.
"""

import ctypes
import platform
import sys
from pathlib import Path

PAGES = [437, 850, 852, 866, 874, 1250, 1251, 1253, 1254, 1255, 1256, 1257, 1258,
         10000, 28591, 28605]
OUT = Path(__file__).resolve().parent.parent / "gridcore" / "src" / "codepage" / "tables.rs"


def decode(page: int, byte: int) -> int:
    kernel32 = ctypes.windll.kernel32
    buf = ctypes.create_unicode_buffer(4)
    n = kernel32.MultiByteToWideChar(page, 0, bytes([byte]), 1, buf, 4)
    if n != 1:
        return 0xFFFD
    cp = ord(buf[0])
    if 0xE000 <= cp <= 0xF8FF:
        return 0xFFFD
    return cp


def main() -> None:
    if sys.platform != "win32":
        sys.exit("gen_codepages.py reads the code pages from Windows itself; run it on Windows")
    for page in PAGES:
        for b in range(0x80):
            if decode(page, b) != b:
                sys.exit(f"code page {page}: byte {b:#04x} is not ASCII")
    lines = [
        "// @generated by tools/gen_codepages.py from Windows' own code pages",
        f"// (MultiByteToWideChar, {platform.platform()}); do not edit by hand.",
        "// An undefined byte, or one Windows reads as a private-use character, is",
        "// U+FFFD.",
        "",
        "/// Each code page's characters for bytes 0x80-0xFF, by page number.",
        "#[rustfmt::skip]",
        "pub(super) const PAGES: &[(u16, [char; 128])] = &[",
    ]
    for page in PAGES:
        lines.append(f"    (")
        lines.append(f"        {page},")
        lines.append("        [")
        chars = [decode(page, b) for b in range(0x80, 0x100)]
        for row in range(0, 128, 8):
            cells = " ".join(f"'\\u{{{c:04X}}}'," for c in chars[row:row + 8])
            lines.append(f"            {cells}")
        lines.append("        ],")
        lines.append("    ),")
    lines.append("];")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
