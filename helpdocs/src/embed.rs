//! Building a manual into a binary (#1856), for a host's build script: the
//! files of `docs/manual/<editor>/` as a Rust source holding
//! `pub static MANUAL: &[(&str, &[u8])]`, one `include_bytes!` per file, which
//! the host `include!`s and passes to [`crate::locate::load`]. A missing
//! directory (a crate built outside the checkout) gives an empty list.

use std::io;
use std::path::{Path, PathBuf};

/// The files of the bundle in `dir`: bundle path (`images/x.png`) and the
/// file's path, sorted by bundle path. Empty when `dir` cannot be listed.
pub fn files(dir: &Path) -> Vec<(String, PathBuf)> {
    let mut out: Vec<(String, PathBuf)> = crate::bundle::files(dir)
        .unwrap_or_default()
        .into_iter()
        .map(|(rel, _)| {
            let path = dir.join(&rel);
            (rel, path)
        })
        .collect();
    out.sort();
    out
}

/// The Rust source embedding `files` ([`files`]'s list).
pub fn source(files: &[(String, PathBuf)]) -> String {
    let mut s = String::from(
        "// Generated by helpdocs::embed from docs/manual (#1856). Do not edit.\n\
         pub static MANUAL: &[(&str, &[u8])] = &[\n",
    );
    for (rel, path) in files {
        let path = path.to_string_lossy();
        s.push_str(&format!("    ({rel:?}, include_bytes!({path:?})),\n"));
    }
    s.push_str("];\n");
    s
}

/// Write the source embedding the bundle in `manual_dir` to `out_file`, and
/// return the files it embeds.
pub fn write_embed(manual_dir: &Path, out_file: &Path) -> io::Result<Vec<PathBuf>> {
    let files = files(manual_dir);
    std::fs::write(out_file, source(&files))?;
    Ok(files.into_iter().map(|(_, p)| p).collect())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Manual;

    fn fixture() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixture/word")
    }

    #[test]
    fn the_list_round_trips_through_from_files() {
        let dir = fixture();
        let list = files(&dir);
        let rels: Vec<&str> = list.iter().map(|(r, _)| r.as_str()).collect();
        assert!(rels.contains(&"contents.txt"), "{rels:?}");
        assert!(rels.contains(&"home.md"), "{rels:?}");
        assert!(rels.contains(&"images/ribbon.png"), "{rels:?}");
        let mut sorted = rels.clone();
        sorted.sort();
        assert_eq!(rels, sorted);
        // What `include_bytes!` would hold is each path's bytes.
        let embedded: Vec<(String, Vec<u8>)> = list
            .iter()
            .map(|(r, p)| (r.clone(), std::fs::read(p).unwrap()))
            .collect();
        assert_eq!(
            Manual::from_files(embedded),
            Manual::load(&dir).unwrap(),
            "the embedded list is the bundle"
        );
    }

    #[test]
    fn the_source_has_one_include_per_file() {
        let list = vec![
            ("contents.txt".to_string(), PathBuf::from("/m/contents.txt")),
            (
                "images/a b.png".to_string(),
                PathBuf::from(r"C:\m\images\a b.png"),
            ),
        ];
        let src = source(&list);
        assert!(
            src.contains("pub static MANUAL: &[(&str, &[u8])] = &[\n"),
            "{src}"
        );
        assert!(
            src.contains(r#"    ("contents.txt", include_bytes!("/m/contents.txt")),"#),
            "{src}"
        );
        // A Windows path is escaped as a Rust string.
        assert!(
            src.contains(r#"    ("images/a b.png", include_bytes!("C:\\m\\images\\a b.png")),"#),
            "{src}"
        );
        assert!(src.ends_with("];\n"));
    }

    #[test]
    fn a_missing_directory_embeds_nothing() {
        let out = std::env::temp_dir().join(format!("helpdocs-embed-{}.rs", std::process::id()));
        let files = write_embed(Path::new("/no/such/manual/dir"), &out).unwrap();
        assert!(files.is_empty());
        let src = std::fs::read_to_string(&out).unwrap();
        assert!(src.contains("= &[\n];\n"), "{src}");
        let _ = std::fs::remove_file(&out);
        // The fixture writes one entry per file.
        let files = write_embed(&fixture(), &out).unwrap();
        let src = std::fs::read_to_string(&out).unwrap();
        assert_eq!(src.matches("include_bytes!").count(), files.len());
        let _ = std::fs::remove_file(&out);
    }
}
